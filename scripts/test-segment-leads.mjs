import assert from "node:assert/strict";
import fs from "node:fs";
import ts from "typescript";
import { createRequire } from "node:module";
import { pathToFileURL } from "node:url";
import React from "react";
import { renderToStaticMarkup } from "react-dom/server";
const require=createRequire(import.meta.url);
const dep=name=>pathToFileURL(require.resolve(name)).href;
const source=fs.readFileSync('src/components/site/ExplorePages.tsx','utf8');
const team=source.slice(source.indexOf('function Team('),source.indexOf('function Venue('));
const helpers=`import React from ${JSON.stringify(dep('react'))};
const PageIntro=()=>null,SectionHeading=()=>null,BottomBanner=()=>null,ArrowUpRight=()=>null;
const Link=({children})=>React.createElement('span',{},children);
const ContentImage=({alt})=>React.createElement('span',{},alt);
const teamPortrait=()=>'',teamAvatar=()=>'';
const TeamMarquee=({members})=>React.createElement('aside',{'data-testid':'marquee'},members.map(m=>m.title).join(','));
`;
const js=ts.transpileModule(helpers+team+'export default Team;', {compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022,jsx:ts.JsxEmit.ReactJSX}}).outputText.replace('"react/jsx-runtime"',JSON.stringify(dep('react/jsx-runtime')));
const {default:Team}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const members=[{id:'lead',title:'Chosen lead',show_as_segment_lead:true},{id:'regular',title:'Regular member',show_as_segment_lead:false},{id:'legacy',title:'Unselected legacy member'}];
const render=team=>renderToStaticMarkup(React.createElement(Team,{data:{team,sponsors:[],settings:{about_description:'Our event'}}}));
const html=render(members);
const cards=html.match(/<div class="people-grid team-grid">(.*?)<\/section>/s)?.[1];
assert(cards.includes('Chosen lead'));
assert(!cards.includes('Regular member'));
assert(!cards.includes('Unselected legacy member'));
assert(html.includes('Chosen lead,Regular member,Unselected legacy member'));
assert(!render(members.slice(1)).includes('people-grid team-grid'));
console.log('Passed: only selected leads render in cards; all published members remain in marquee; unselected legacy members stay out; empty lead section is hidden.');
