import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { randomUUID } from "node:crypto";
import { createRequire } from "node:module";
import { pathToFileURL } from "node:url";
import nextEnv from "@next/env";
import ts from "typescript";
import { createClient } from "redis";
nextEnv.loadEnvConfig(process.cwd(),false,{info(){},error(){}});
if (!process.env.REDIS_URL) throw new Error("Set REDIS_URL in ignored local environment configuration.");
process.env.REDIS_KEY_PREFIX = "cye:qa:" + randomUUID() + ":";
const require=createRequire(import.meta.url);
const moduleUrl=s=>"data:text/javascript;base64,"+Buffer.from(s).toString("base64");
const compile=file=>ts.transpileModule(readFileSync(file,"utf8"),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText.replace('import "server-only";','');
const redisUrl=moduleUrl(compile('src/lib/server/redis.ts').replace('"redis"',JSON.stringify(pathToFileURL(require.resolve('redis')).href)));
const limiterUrl=moduleUrl(compile('src/lib/server/rate-limit.ts').replace('"./redis"',JSON.stringify(redisUrl)));
const {redisClient}=await import(redisUrl);
const {consumeRateLimit,rateLimitKey,RATE_LIMIT_SCRIPT}=await import(limiterUrl);
const httpUrl=moduleUrl(compile('src/lib/server/http.ts').replace('"./rate-limit"',JSON.stringify(limiterUrl)));
const {rateLimit,handle}=await import(httpUrl);
const independent=createClient({url:process.env.REDIS_URL,socket:{connectTimeout:5000,reconnectStrategy:false}});
independent.on('error',()=>{});
const keys=[];
try {
  const [first,second]=await Promise.all([redisClient(),redisClient()]);
  assert.equal(first,second,'Concurrent calls reuse one connection, never a local counter');
  await independent.connect();
  const key=rateLimitKey('qa-concurrent','site','private@example.test'); keys.push(key);
  assert(!key.includes('private@example.test'));
  const decisions=await Promise.all(Array.from({length:30},(_,i)=>i%2?consumeRateLimit(key,5,60):independent.eval(RATE_LIMIT_SCRIPT,{keys:[key],arguments:['5','60000']}).then(r=>({allowed:r[0]===1}))));
  assert.equal(decisions.filter(r=>r.allowed).length,5,'Only five requests across independent clients may pass');
  assert.equal(await independent.get(key),'5');
  const ttlBefore=await independent.pTTL(key);
  await new Promise(resolve=>setTimeout(resolve,100));
  assert.equal((await consumeRateLimit(key,5,60)).allowed,false);
  assert((await independent.pTTL(key))<ttlBefore,'Blocked traffic cannot extend the expiry');
  const expiry=rateLimitKey('qa-expiry','site'); keys.push(expiry);
  assert((await consumeRateLimit(expiry,1,1)).allowed);
  assert(!(await consumeRateLimit(expiry,1,1)).allowed);
  await new Promise(resolve=>setTimeout(resolve,1150));
  assert((await consumeRateLimit(expiry,1,1)).allowed,'A new window opens after TTL');
  const identity='qa-'+randomUUID();const request=new Request('https://test.example');
  keys.push(rateLimitKey('qa-http','site',identity));
  const trust=process.env.TRUST_PROXY;process.env.TRUST_PROXY='false';
  await rateLimit(request,'qa-http',1,60,identity);
  const denied=await handle(async()=>{await rateLimit(request,'qa-http',1,60,identity);return Response.json({ok:true});});
  assert.equal(denied.status,429); assert(Number(denied.headers.get('retry-after'))>0);assert.equal(denied.headers.get('cache-control'),'no-store');
  process.env.TRUST_PROXY=trust||'false';
  const failStore=moduleUrl('export const rateLimitKey=()=>"test";export async function consumeRateLimit(){throw Error("sensitive provider error") }');
  const failHttp=await import(moduleUrl(compile('src/lib/server/http.ts').replace('"./rate-limit"',JSON.stringify(failStore))));
  const unavailable=await failHttp.handle(async()=>{await failHttp.rateLimit(request,'qa-failure',1);return Response.json({ok:true});});
  assert.equal(unavailable.status,503);assert.equal(unavailable.headers.get('retry-after'),'5');assert(!(await unavailable.text()).includes('sensitive provider error'));
  console.log('Passed: shared connection setup, atomic quota across 30 concurrent requests/two clients, expiring windows, denied-request TTL preservation, hashed identities, HTTP 429 + Retry-After, and fail-closed sanitized 503 responses. Synthetic Redis keys only.');
} catch {
  console.error('Redis rate-limit tests failed. Provider errors and credentials were suppressed.');process.exitCode=1;
} finally {
  if(independent.isReady && keys.length) await independent.del(keys).catch(()=>{});
  if(independent.isOpen) independent.destroy();
  if(globalThis.cyeRedis?.isOpen) globalThis.cyeRedis.destroy();
}
